from functools import lru_cache
from typing import List
import torch

def _poly(x:torch.Tensor,c:List[float],leading_one:bool=False):
    v=torch.ones_like(x) if leading_one else torch.zeros_like(x)
    for a in c:v=v*x+a
    return v

